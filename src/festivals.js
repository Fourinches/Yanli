function nthWeekday(year, month, weekday, nth) {
  const first = new Date(year, month - 1, 1);
  const shift = (weekday - first.getDay() + 7) % 7;
  return 1 + shift + (nth - 1) * 7;
}

function lastWeekday(year, month, weekday) {
  const last = new Date(year, month, 0).getDate();
  const date = new Date(year, month - 1, last);
  const shift = (date.getDay() - weekday + 7) % 7;
  return last - shift;
}

export function getExtraFestivals(year, month, day) {
  const key = `${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
  const names = FIXED[key] ? [...FIXED[key]] : [];

  if (month === 5 && day === nthWeekday(year, 5, 0, 2)) names.push("母亲节");
  if (month === 6 && day === nthWeekday(year, 6, 0, 3)) names.push("父亲节");
  if (month === 11 && day === nthWeekday(year, 11, 4, 4)) names.push("感恩节");
  if (month === 1 && day === lastWeekday(year, 1, 0)) names.push("国际麻风节");
  if (month === 10 && day === nthWeekday(year, 10, 1, 2)) names.push("加拿大感恩节");

  return names;
}
